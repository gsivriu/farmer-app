CREATE OR REPLACE FUNCTION public.is_admin(uid uuid)
RETURNS boolean
LANGUAGE sql
STABLE
AS $$
  select exists (
    select 1 from public.profiles p
    where p.id = uid and p.role = 'admin'
  );
$$;

CREATE OR REPLACE FUNCTION public.generate_contract_no(prefix text DEFAULT 'AMRP'::text)
RETURNS text
LANGUAGE plpgsql
AS $$
declare
  n bigint;
begin
  n := nextval('public.contract_seq');
  return prefix || '-' || lpad(n::text, 5, '0');
end;
$$;

CREATE OR REPLACE FUNCTION public.assign_contract_no_on_accept()
RETURNS trigger
LANGUAGE plpgsql
AS $$
begin
  if (new.status = 'accepted')
     and (old.status is distinct from new.status)
     and new.contract_no is null then
    new.contract_no := public.generate_contract_no('AMRP');
    new.accepted_at := now();
  end if;
  return new;
end;
$$;

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  INSERT INTO public.profiles (id, email, role, status)
  VALUES (NEW.id, NEW.email, 'farmer', 'active')
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$$;

-- ============================================================
-- Triggers
-- ============================================================

CREATE OR REPLACE TRIGGER trg_assign_contract_no
    BEFORE UPDATE ON public.bids
    FOR EACH ROW EXECUTE FUNCTION public.assign_contract_no_on_accept();

CREATE OR REPLACE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

