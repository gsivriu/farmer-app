-- Policies: bids
CREATE POLICY admin_select_all_bids ON public.bids
    FOR SELECT USING (public.is_admin(auth.uid()));

CREATE POLICY admin_update_all_bids ON public.bids
    FOR UPDATE USING (public.is_admin(auth.uid()))
    WITH CHECK (public.is_admin(auth.uid()));

CREATE POLICY farmer_insert_own_bids ON public.bids
    FOR INSERT WITH CHECK (auth.uid() = farmer_id);

CREATE POLICY farmer_select_own_bids ON public.bids
    FOR SELECT USING (auth.uid() = farmer_id);

CREATE POLICY farmer_update_own_bids ON public.bids
    FOR UPDATE
    USING ((auth.uid() = farmer_id) AND (status = 'countered'::text))
    WITH CHECK ((auth.uid() = farmer_id) AND (status = ANY (ARRAY['farmer_countered'::text, 'accepted'::text, 'rejected'::text])));

-- Policies: commodities
CREATE POLICY admin_write_commodities ON public.commodities
    FOR ALL USING (public.is_admin(auth.uid()))
    WITH CHECK (public.is_admin(auth.uid()));

CREATE POLICY authenticated_read_commodities ON public.commodities
    FOR SELECT TO authenticated USING (true);

-- Policies: farmer_rewards
CREATE POLICY farmer_rewards_select_own ON public.farmer_rewards
    FOR SELECT USING (farmer_id = auth.uid());

-- Policies: profiles
CREATE POLICY admin_read_all_profiles ON public.profiles
    FOR SELECT TO authenticated USING (public.is_admin(auth.uid()));

CREATE POLICY admin_update_profiles ON public.profiles
    FOR UPDATE USING (public.is_admin(auth.uid()))
    WITH CHECK (public.is_admin(auth.uid()));

CREATE POLICY users_can_read_own_profile ON public.profiles
    FOR SELECT TO authenticated USING (id = auth.uid());

-- Policies: silo_price_configs
CREATE POLICY admin_write_silo_prices ON public.silo_price_configs
    FOR ALL USING (public.is_admin(auth.uid()))
    WITH CHECK (public.is_admin(auth.uid()));

CREATE POLICY authenticated_read_silo_prices ON public.silo_price_configs
    FOR SELECT TO authenticated USING (true);

