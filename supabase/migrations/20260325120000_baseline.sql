CREATE TABLE IF NOT EXISTS public.profiles (
    id uuid NOT NULL,
    email text,
    role text NOT NULL DEFAULT 'farmer'::text,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    status text NOT NULL DEFAULT 'active'::text,
    invited_by uuid,
    invited_at timestamp with time zone,
    sharp_id text,
    full_name text,
    telefon text,
    judet text,
    CONSTRAINT profiles_pkey PRIMARY KEY (id),
    CONSTRAINT profiles_status_check CHECK (status = ANY (ARRAY['active'::text, 'disabled'::text])),
    CONSTRAINT profiles_id_fkey FOREIGN KEY (id) REFERENCES auth.users(id),
    CONSTRAINT profiles_invited_by_fkey FOREIGN KEY (invited_by) REFERENCES auth.users(id)
);

CREATE TABLE IF NOT EXISTS public.bids (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    farmer_id uuid DEFAULT auth.uid(),
    product text NOT NULL DEFAULT 'Not Null'::text,
    quantity numeric,
    price numeric,
    delivery_start date,
    delivery_end date,
    status text,
    created_at timestamp with time zone DEFAULT now(),
    parity text,
    freight_cost numeric,
    counter_price numeric,
    farmer_email text,
    final_price numeric,
    contract_no text,
    accepted_at timestamp with time zone,
    delivery_location text,
    loading_location text,
    CONSTRAINT bids_pkey PRIMARY KEY (id),
    CONSTRAINT bids_contract_no_key UNIQUE (contract_no)
);

CREATE TABLE IF NOT EXISTS public.farmer_rewards (
    id bigint NOT NULL DEFAULT nextval('public.farmer_rewards_id_seq'::regclass),
    farmer_id uuid,
    reward_type text NOT NULL,
    unlocked_at timestamp with time zone DEFAULT now(),
    used boolean DEFAULT false,
    target_t integer,
    bonus_eur numeric,
    bonus_tonnes integer,
    lock_product text,
    lock_days integer,
    lock_limit_tonnes integer,
    CONSTRAINT farmer_rewards_pkey PRIMARY KEY (id),
    CONSTRAINT farmer_rewards_farmer_id_fkey FOREIGN KEY (farmer_id) REFERENCES auth.users(id)
);

CREATE TABLE IF NOT EXISTS public.silo_price_configs (
    id uuid NOT NULL DEFAULT extensions.uuid_generate_v4(),
    silo_name text NOT NULL,
    product_type text NOT NULL,
    offset_value numeric NOT NULL,
    currency text NOT NULL DEFAULT 'EUR'::text,
    updated_at timestamp with time zone DEFAULT now(),
    manual_price numeric,
    notes text,
    CONSTRAINT silo_price_configs_pkey PRIMARY KEY (id),
    CONSTRAINT unique_silo_product UNIQUE (silo_name, product_type)
);

CREATE TABLE IF NOT EXISTS public.commodities (
    id uuid NOT NULL DEFAULT gen_random_uuid(),
    name text NOT NULL,
    price numeric NOT NULL,
    last_updated timestamp with time zone DEFAULT now(),
    CONSTRAINT commodities_pkey PRIMARY KEY (id),
    CONSTRAINT commodities_name_key UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS public.rate_limits (
    key text NOT NULL,
    count integer NOT NULL DEFAULT 1,
    window_start timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT rate_limits_pkey PRIMARY KEY (key)
);

-- Non-unique index
CREATE INDEX IF NOT EXISTS rate_limits_window_idx ON public.rate_limits USING btree (window_start);

